-- PostgreSQL 16+. Executar em banco vazio; nao remove tabelas existentes.
-- Base de integracao: preserva inconsistencias de negocio para a Parte 4.
BEGIN;

CREATE TABLE fornecedor (
    idfornecedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_origem VARCHAR(25) UNIQUE,
    razao_social VARCHAR(255) NOT NULL,
    cadastro_provisorio BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE produtos_filial (
    filial_id INTEGER NOT NULL,
    produto_id VARCHAR(25) NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    estoque NUMERIC(18,4) NOT NULL DEFAULT 0,
    preco_unitario NUMERIC(18,4) NOT NULL DEFAULT 0,
    preco_compra NUMERIC(18,4) NOT NULL DEFAULT 0,
    preco_venda NUMERIC(18,4) NOT NULL DEFAULT 0,
    idfornecedor BIGINT REFERENCES fornecedor(idfornecedor),
    PRIMARY KEY (filial_id, produto_id)
);

CREATE TABLE pedido_compra (
    pedido_id BIGINT NOT NULL,
    data_pedido DATE NOT NULL,
    item INTEGER NOT NULL,
    produto_id VARCHAR(25) NOT NULL,
    descricao_produto VARCHAR(255),
    ordem_compra BIGINT NOT NULL,
    qtde_pedida NUMERIC(18,4) NOT NULL,
    filial_id INTEGER NOT NULL,
    data_entrega DATE,
    qtde_entregue NUMERIC(18,4) NOT NULL DEFAULT 0,
    qtde_pendente NUMERIC(18,4) GENERATED ALWAYS AS (qtde_pedida - qtde_entregue) STORED,
    preco_compra NUMERIC(18,4) NOT NULL,
    fornecedor_id BIGINT REFERENCES fornecedor(idfornecedor),
    PRIMARY KEY (filial_id, pedido_id, produto_id, item)
);

CREATE TABLE entradas_mercadoria (
    data_entrada DATE NOT NULL,
    nro_nfe VARCHAR(255) NOT NULL,
    item INTEGER NOT NULL,
    produto_id VARCHAR(25) NOT NULL,
    descricao_produto VARCHAR(255),
    ordem_compra BIGINT NOT NULL,
    qtde_recebida NUMERIC(18,4) NOT NULL,
    filial_id INTEGER NOT NULL,
    custo_unitario NUMERIC(18,4) NOT NULL,
    PRIMARY KEY (filial_id, ordem_compra, item, produto_id, nro_nfe)
);

CREATE TABLE venda (
    venda_id BIGINT NOT NULL,
    data_emissao DATE NOT NULL,
    horariomov TIME NOT NULL DEFAULT '00:00:00',
    produto_id VARCHAR(25) NOT NULL,
    qtde_vendida NUMERIC(18,4) NOT NULL,
    valor_unitario NUMERIC(18,4) NOT NULL,
    filial_id INTEGER NOT NULL,
    item INTEGER NOT NULL,
    unidade_medida VARCHAR(3),
    PRIMARY KEY (filial_id, venda_id, data_emissao, produto_id, item, horariomov)
);

-- Sem FKs de movimentos para produtos/pedidos nesta base de integracao:
-- ha vendas sem cadastro e ordens ausentes/zero na origem. As consultas V03,
-- V04 e V06 identificam essas ocorrencias sem descartar movimentos.
-- FKs de fornecedores sao aplicadas, pois o mapeamento e verificavel.
CREATE INDEX venda_data_produto_idx ON venda(data_emissao, produto_id);
CREATE INDEX pedido_ordem_idx ON pedido_compra(ordem_compra, filial_id, produto_id, item);

CREATE TABLE importacao_lote (
    sha256 CHAR(64) PRIMARY KEY,
    arquivo VARCHAR(255) NOT NULL,
    importado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE importacao_linha (
    sha256 CHAR(64) NOT NULL REFERENCES importacao_lote(sha256),
    aba VARCHAR(40) NOT NULL,
    linha INTEGER NOT NULL,
    dados JSONB NOT NULL,
    campos_extras JSONB,
    PRIMARY KEY (sha256, aba, linha)
);
COMMIT;
